import SwiftUI
import StudyDomain
import StudyDesignSystem

struct DocumentReadyView: View {
    @EnvironmentObject private var model: AppModel
    let ready: AppModel.ReadyDocument
    @State private var confirmDelete = false

    var body: some View {
        ScrollView {
            ReadingColumn {
                VStack(alignment: .leading, spacing: StudyDesign.spacingXL) {
                    header
                    if let error = model.libraryError {
                        ErrorBanner(message: error) { model.libraryError = nil }
                    }
                    if model.activeProvider == nil {
                        providerNotice
                    }
                    qualityCard
                    if !ready.quality.warnings.isEmpty {
                        warningsCard
                    }
                    studyActions
                    if let last = ready.lastSession {
                        sessionCard(last)
                    }
                }
                .padding(.vertical, StudyDesign.spacingXXL)
            }
        }
        .navigationTitle(ready.document.name)
        .toolbar {
            ToolbarItem(placement: .navigation) {
                Button {
                    model.selectedDocumentID = nil
                    model.readyDocument = nil
                    Task { await model.refreshDocuments() }
                } label: {
                    Label("Documents", systemImage: "chevron.left")
                }
                .help("Back to the library")
            }
        }
        .confirmationDialog("Delete this document?", isPresented: $confirmDelete) {
            Button("Delete \"\(ready.document.name)\" and its history", role: .destructive) {
                Task {
                    await model.deleteDocument(ready.document.id)
                    model.selectedDocumentID = nil
                    model.readyDocument = nil
                }
            }
            Button("Cancel", role: .cancel) {}
        } message: {
            Text("The app-owned copy, extracted passages, topics, sessions and answers will be removed.")
        }
    }

    private var header: some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack(spacing: 8) {
                Text(ready.document.fileType.displayName)
                    .font(.caption.weight(.semibold))
                    .padding(.horizontal, 8)
                    .padding(.vertical, 3)
                    .background(.quaternary.opacity(0.6), in: Capsule())
                if let language = ready.document.language {
                    Text(language.uppercased())
                        .font(.caption)
                        .foregroundStyle(.secondary)
                }
            }
            Text(ready.document.name)
                .font(StudyDesign.titleFont)
                .textSelection(.enabled)
            Text("Imported \(ready.document.importedAt.formatted(date: .abbreviated, time: .shortened)) · \(ready.sectionCount) sections · \(ready.topicCount) topics")
                .font(.callout)
                .foregroundStyle(.secondary)
        }
    }

    private var providerNotice: some View {
        StudyCard {
            HStack(alignment: .top, spacing: 14) {
                Image(systemName: "sparkles")
                    .font(.system(size: 20))
                    .foregroundStyle(.orange)
                    .padding(.top, 2)
                VStack(alignment: .leading, spacing: 6) {
                    Text("No AI model is configured")
                        .font(StudyDesign.headingFont)
                    Text("Questions and assessments are generated by the provider you choose. The app sends only the passages needed for the current step.")
                        .font(.callout)
                        .foregroundStyle(.secondary)
                        .fixedSize(horizontal: false, vertical: true)
                }
                Spacer()
                Button("Open Settings") {
                    model.sidebarSelection = .settings
                    model.study = nil
                }
                .buttonStyle(.borderedProminent)
            }
        }
    }

    private var qualityCard: some View {
        StudyCard {
            VStack(alignment: .leading, spacing: 14) {
                SectionHeader(
                    title: "Source preparation",
                    subtitle: "How the document was processed and what was extracted"
                )
                
                HStack(spacing: 24) {
                    MetricView(label: "Pages", value: ready.quality.pagesProcessed > 0 ? "\(ready.quality.pagesProcessed)" : "—")
                    MetricView(label: "Paragraphs", value: "\(ready.quality.paragraphsExtracted)")
                    MetricView(label: "Characters", value: "\(ready.quality.charactersExtracted)")
                    MetricView(label: "Sections", value: "\(ready.sectionCount)")
                }
                
                Text(ready.quality.summary)
                    .font(.callout)
                    .foregroundStyle(.secondary)
                
                if ready.quality.pagesRequiringOCR > 0 {
                    Label("OCR text is marked in the passages and is excluded when recognition is unreliable.", systemImage: "text.viewfinder")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                }
            }
        }
    }

    private var warningsCard: some View {
        StudyCard {
            VStack(alignment: .leading, spacing: 10) {
                Label("Extraction limitations", systemImage: "exclamationmark.triangle")
                    .font(StudyDesign.headingFont)
                    .foregroundStyle(.orange)
                ForEach(ready.quality.warnings, id: \.self) { warning in
                    HStack(alignment: .top, spacing: 8) {
                        Text("•")
                            .foregroundStyle(.secondary)
                        Text(warning)
                            .font(.callout)
                            .foregroundStyle(.secondary)
                            .fixedSize(horizontal: false, vertical: true)
                    }
                }
            }
        }
    }

    private var studyActions: some View {
        VStack(alignment: .leading, spacing: 14) {
            if ready.topicCount == 0 {
                StudyCard {
                    Label("No topic with reliable source passages was found, so studying is blocked rather than guessing.", systemImage: "exclamationmark.triangle")
                        .font(.callout)
                        .foregroundStyle(.orange)
                }
            } else if model.activeProvider == nil {
                StudyCard {
                    Text("Configure and test an AI model before starting a session.")
                        .font(.callout)
                        .foregroundStyle(.secondary)
                }
            } else {
                StudyCard {
                    VStack(alignment: .leading, spacing: 14) {
                        SectionHeader(
                            title: "Start studying",
                            subtitle: "Choose a focus within the document or study the entire document"
                        )
                        ScopePickerView(
                            snapshotId: ready.snapshotId,
                            showsModePicker: true,
                            confirmTitle: "Start studying"
                        ) { scope, mode in
                            Task { await model.startStudy(mode: mode, scopeId: scope.id) }
                        }
                    }
                }
            }

            HStack(spacing: 12) {
                if ready.activeSessionID != nil {
                    Button {
                        Task { await model.resumeStudy() }
                    } label: {
                        Label("Resume session", systemImage: "arrow.clockwise")
                    }
                    .buttonStyle(.bordered)
                    .disabled(model.activeProvider == nil)
                }
                Button {
                    model.requestReplacePanel(for: ready.document.id)
                } label: {
                    Label("Import updated version…", systemImage: "arrow.triangle.2.circlepath")
                }
                .buttonStyle(.bordered)
                .disabled(model.importing != nil)
            }
            Text("A replaced file becomes a new document version. Previous questions, answers and their sources keep the version they used.")
                .font(.caption)
                .foregroundStyle(.secondary)
                .fixedSize(horizontal: false, vertical: true)
        }
    }

    private func sessionCard(_ last: StudySession) -> some View {
        StudyCard {
            VStack(alignment: .leading, spacing: 10) {
                SectionHeader(
                    title: "Last session",
                    subtitle: "\(last.mode.displayName) · started \(last.startedAt.formatted(date: .abbreviated, time: .shortened)) · \(last.state == .active ? "in progress" : "finished")"
                )
                if last.finishedAt == nil {
                    Label("An interrupted session keeps its question and draft. Resume continues from there.", systemImage: "clock.arrow.circlepath")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                }
            }
        }
    }
}
